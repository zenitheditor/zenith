//! Write the code-point coverage of each fallback face to
//! `$OUT_DIR/coverage.rs`.
//!
//! A face covers a code point when `ttf_parser::Face::glyph_index` maps it.
//! The shaper runs the same test with the same `ttf-parser` version, so the
//! table names exactly the face the shaper picks. A host that does not
//! embed the faces reads the table to name the file a glyph needs.

use std::error::Error;
use std::fmt::Write as _;
use std::path::PathBuf;

/// The static name and the file of each face, in chain order.
const FACES: [(&str, &str); 4] = [
    ("ARABIC", "NotoSansArabic-Regular.ttf"),
    ("HEBREW", "NotoSansHebrew-Regular.ttf"),
    ("CJK_SC", "NotoSansCJKsc-Fallback.otf"),
    ("EMOJI", "NotoEmoji-Regular.ttf"),
];

fn main() -> Result<(), Box<dyn Error>> {
    println!("cargo::rerun-if-changed=build.rs");
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR")?);
    let mut out = String::from("// Generated by build.rs. Do not edit.\n");
    for (name, file) in FACES {
        println!("cargo::rerun-if-changed=fonts/{file}");
        let path = manifest.join("fonts").join(file);
        let bytes =
            std::fs::read(&path).map_err(|e| format!("cannot read {}: {e}", path.display()))?;
        let face = ttf_parser::Face::parse(&bytes, 0)
            .map_err(|e| format!("cannot parse {}: {e}", path.display()))?;
        let ranges = coverage(&face);
        writeln!(out, "\n/// The code points `{file}` maps.")?;
        writeln!(
            out,
            "pub(crate) static {name}: [(u32, u32); {}] = [",
            ranges.len()
        )?;
        for (start, end) in ranges {
            writeln!(out, "    (0x{start:X}, 0x{end:X}),")?;
        }
        writeln!(out, "];")?;
    }
    let dest = PathBuf::from(std::env::var("OUT_DIR")?).join("coverage.rs");
    std::fs::write(&dest, out).map_err(|e| format!("cannot write {}: {e}", dest.display()))?;
    Ok(())
}

/// The sorted inclusive code-point ranges `face` maps.
fn coverage(face: &ttf_parser::Face<'_>) -> Vec<(u32, u32)> {
    let mut ranges: Vec<(u32, u32)> = Vec::new();
    for ch in (0..=u32::from(char::MAX)).filter_map(char::from_u32) {
        if face.glyph_index(ch).is_none() {
            continue;
        }
        let cp = u32::from(ch);
        match ranges.last_mut() {
            Some((_, end)) if *end + 1 == cp => *end = cp,
            _ => ranges.push((cp, cp)),
        }
    }
    ranges
}
